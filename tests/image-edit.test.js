const assert = require('node:assert/strict');
const { requestImageEdit, selectImageSources, asksImageEdit, allowsMultiImageEdit, isExplicitImageOperation } = require('./build/assistant/imageEditing.js');
(async () => {
  const original = { name: '原图', dataUrl: 'data:image/png;base64,AQID' };
  const edited = { name: '改过的图', dataUrl: 'data:image/png;base64,BAUG', root: [original] };
  assert.equal(asksImageEdit('把背景换成夜景，人物别动', true), true);
  assert.equal(asksImageEdit('再暗一点', true, true), true);
  assert.equal(asksImageEdit('把设置换成深色', true, true), false);
  assert.equal(asksImageEdit('怎么实现图生图？', true), false);
  assert.equal(isExplicitImageOperation('把这张图改成下雨'), true);
  assert.equal(allowsMultiImageEdit('换成夜景'), false);
  assert.equal(allowsMultiImageEdit('把两张图合成一张'), true);
  assert.deepEqual(selectImageSources('用原图重来', [], [edited]), [original]);
  assert.deepEqual(selectImageSources('再暗一点', [], [edited]), [edited]);
  assert.deepEqual(selectImageSources('改这个', [original], [edited]), [original]);
  let request;
  global.fetch = async (url, options) => {
    request = { url, ...options };
    return new Response(JSON.stringify({ data: [{ b64_json: 'BwgJ' }] }));
  };
  const opts = { base: 'https://example.invalid/v1/', apiKey: 'test-key', model: 'image-model', prompt: '换背景', images: [original] };
  assert.deepEqual(await requestImageEdit(opts), { base64: 'BwgJ', model: 'image-model' });
  assert.equal(request.url, 'https://example.invalid/v1/images/edits');
  assert.equal(request.redirect, 'error');
  assert.equal(request.headers.Authorization, 'Bearer test-key');
  assert.equal(request.body.get('prompt'), '换背景');
  assert.deepEqual([...new Uint8Array(await request.body.get('image').arrayBuffer())], [1, 2, 3]);
  await requestImageEdit({ ...opts, images: [original, edited] });
  assert.equal(request.body.getAll('image[]').length, 2);
  const mask = new Blob([new Uint8Array([8])], { type: 'image/png' });
  await requestImageEdit({ ...opts, mask });
  assert.equal(request.body.get('mask').type, 'image/png');
  await assert.rejects(requestImageEdit({ ...opts, images: [original, edited], mask }), /只选一张/);
  const abort = new AbortController();
  global.fetch = (_url, { signal }) => new Promise((_, reject) => signal.addEventListener('abort', () => reject(new Error('abort'))));
  const cancelled = requestImageEdit({ ...opts, signal: abort.signal });
  abort.abort();
  await assert.rejects(cancelled, /已取消改图/);
  let calls = 0;
  global.fetch = async () => { calls++; return new Response('', { status: 404 }); };
  await assert.rejects(requestImageEdit(opts), /未提供可用的图像编辑接口/);
  assert.equal(calls, 1, '不尝试文生图或其他供应商');
  console.log('image-edit: all assertions passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
