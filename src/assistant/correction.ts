/**
 * 识别"用户在纠正你"（纯函数，可单测）。
 *
 * 为什么需要它：记忆纠正原来完全靠后台提取器"恰好"跑一轮才发现，
 * 而提取是攒够 6 条消息才触发的 —— 用户说"你记错了，我不写小说了"之后，
 * 模型可能还会带着错的记忆聊好几轮，画像也跟着歪。
 *
 * 这里只在用户消息里做**保守**的句式识别（宁可漏，不要误判成纠正而频繁重算），
 * 命中就立刻跑一次提取 + 强制重算画像。
 */

/** 明显在纠正/否认/要求别记的说法 */
const CORRECTION_PATTERNS: RegExp[] = [
  /记错|记反|记混|记岔/,
  /不是这样|不是这个意思|不是这回事|不是那个意思/,
  /我没说过|我没讲过|我没提过|我什么时候说过/,
  /搞错|弄错|认错人/,
  /别记(这个|住|了)?|不要记|不用记|别再记/,
  /我说的是|我讲的是|我说过的是/,
  /不是.{0,12}而是/,
  /你记的[^。！？!?]{0,16}(不对|错了|有问题)/,
];

export function detectCorrection(text: string): boolean {
  const t = (text || "").trim();
  if (!t || t.length > 200) return false;
  return CORRECTION_PATTERNS.some((re) => re.test(t));
}
