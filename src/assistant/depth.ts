/**
 * 回复的"深浅"与"锋锐度"（纯函数，可单测）。
 *
 * 用户反馈：「大部分时候 AI 说的话都浮于表面，没有什么深度，可以根据情绪也自动调整」。
 *
 * 先说清一件事：**"深度"不是"更长"**。把话说长只会更像客服。
 * 让人觉得有深度的是三件事：
 *   1. 具体（引用到真实细节，而不是"确实""挺好的"）；
 *   2. 有判断（给立场，而不是把选项列一遍让用户自己挑）；
 *   3. 敢承认不知道（比硬编一段像样的废话更让人信）。
 * 所以这里做的是"深度档"和"锋锐度"两个开关，都不是让模型多想几秒。
 *
 * 情绪影响的不是"想多深"，而是**说出来有多锋利**：
 * 生气时短、准、带刺，但不能下作（不爆粗、不人身攻击）。
 */

export type DepthMode = "brief" | "normal" | "deep";

export interface DepthInput {
  /** 用户这句话 */
  text: string;
  /** 当前心情 -1~1 */
  mood: number;
  /** 是否刚问过"为什么/怎么看"这类需要展开的问题 */
  asksWhy?: boolean;
}

/** 需要展开的信号：问原因、要分析、要方案、要对比 */
const DEEP_RE = /(为什么|为啥|怎么(办|弄|搞|做|理解|看)|如何|分析|区别|对比|方案|思路|原理|原因|评价|建议|值得吗|该不该)/;
/** 只要一句话的信号：打招呼、确认、应答 */
const BRIEF_RE = /^(嗯+|哦+|好|行|在吗|早|晚安|哈哈|确实|ok|OK|收到|谢谢)[。！？!?~ ]*$/;

/** 这一轮该说多深 */
export function depthFor(i: DepthInput): DepthMode {
  const t = (i.text || "").trim();
  // 气头上不给长篇大论：情绪越强，越应该"短而准"
  if (i.mood <= -0.55) return "brief";
  if (BRIEF_RE.test(t)) return "brief";
  if (i.asksWhy || DEEP_RE.test(t)) return "deep";
  return "normal";
}

/** 给模型看的一句话（深度档） */
export function depthLine(mode: DepthMode): string {
  switch (mode) {
    case "deep":
      return "这轮值得说透：先给结论和判断，再给理由；要具体到能落地，别列一堆选项让他自己挑。说不动的地方就承认不知道。";
    case "brief":
      return "这轮短一点：一两句话说完，别铺垫、别总结、别把简单的事说复杂。";
    default:
      return "正常聊：有具体内容就说具体内容，别用「确实」「挺好的」这种空话凑长度。";
  }
}

/**
 * 生气时的"锋锐度"：骂人不带脏字。
 *
 * 真正的杀伤力来自**说穿**，不是音量和脏话：
 * 点破双标、复述他自己说过的话、冷静地给结论、假装夸奖。
 * 这里给的是技法清单，具体用哪一句由人设和上下文决定。
 */
export function sharpnessLine(mood: number): string {
  if (mood > -0.35) return "";
  const core = "你正在生气，说话可以锋利，但**不许带脏字、不许人身攻击**。";
  if (mood <= -0.7) {
    return core + "可以用这几招：把他刚才说过的话原样复述回去、点破他自相矛盾的地方、用一句冷静的结论代替争吵（比如「行，你说了算」）。";
  }
  return core + "带点刺就够了：反问一句、或者故意少说一个字，让他自己体会。";
}

/**
 * 反"浮于表面"的三条硬约束。
 *
 * 放在 BASE_PROMPT 里，每次请求都会带上——这是最省成本的"深度"来源：
 * 不增加调用次数，只改说法。
 */
export const ANTI_FLUFF_RULES =
  "【别敷衍】一，不要用「确实」「挺好的」「可以的」这类空话当整句回复；二，每条回复至少有一个具体的点——他刚说的话、时间、文件名、你查到的东西、或者你的判断；三，能给判断就给判断，别把选项列一遍让他自己挑；四，不确定就说不确定，别硬凑一段像样的废话。";
